def apply_variant(rows, spec):
    out = []
    for r in rows:
        o = spec.get(r["case_id"])
        if o is None:
            out.append(dict(r, band=None))
        else:
            out.append(dict(r, lr=o["lr"], target=o["target"], band=o["band"]))
    return out


def signed_err(r):
    """Signed log-odds error; against a band, the distance to the nearer edge (0 inside)."""
    y = logit_clipped(r["post"])
    if r.get("band"):
        lo, hi = (logit_clipped(x) for x in r["band"])
        return y - hi if y > hi else (y - lo if y < lo else 0.0)
    return y - logit_clipped(r["target"])


def ratio_cells_rows(rows):
    """F1 ratio with the LR taken from the rows (so a variant's LR enters log DOR)."""
    g, lr = {}, {}
    for r in rows:
        if r["condition"] not in cf.FIT_CONDS:
            continue
        g.setdefault((r["model"], r["scenario"]), {"pos": [], "neg": []})[r["result"]].append(logit_clipped(r["post"]))
        lr.setdefault(r["scenario"], {})[r["result"]] = r["lr"]
    out = []
    for (m, s), d in sorted(g.items()):
        if d["pos"] and d["neg"]:
            dx = math.log(lr[s]["pos"]) - math.log(lr[s]["neg"])
            dy = statistics.mean(d["pos"]) - statistics.mean(d["neg"])
            out.append({"model": m, "scenario": s, "dy": dy, "log_dor": dx, "ratio": dy / dx})
    return out


def f4(rows, cases, n_boot, mac, gen_dir, variants=None):
    specs = alt_specs(cases, load_json(ALT))
    variants = variants or list(specs)
    models = cf.models_of(rows)
    out, b3 = [], []
    for vname in variants:
        vr = apply_variant(rows, specs[vname])
        cells = ratio_cells_rows(vr)
        fit_variant = vname not in ("observed_ci_band",)  # same LRs as "observed"
        for m in models + ["ALL"]:
            mr = [r for r in vr if m == "ALL" or r["model"] == m]
            pos = [signed_err(r) for r in mr if r["result"] == "pos"]
            mc = [c for c in cells if m == "ALL" or c["model"] == m]
            row = {"variant": vname, "model": m, "n_pos": len(pos), "over_med_lod": statistics.median(pos),
                   "over_pct_above": 100 * sum(x > 0 for x in pos) / len(pos),
                   "ratio_med": statistics.median(c["ratio"] for c in mc), "ratio_n_gt1": sum(c["ratio"] > 1 for c in mc),
                   "ratio_n": len(mc)}
            if m != "ALL" and fit_variant:
                f = cf.fit_cell([r for r in mr if r["condition"] in cf.FIT_CONDS], n_boot, f"alt-{vname}-{m}")
                row.update(b=f["b"], b_lo=f["b_lo"], b_hi=f["b_hi"], a=f["a"])
            out.append(row)
        # B3 negative (the false-reassurance example), V N B S pooled over models, as make_tables.neg_scenario_table
        b3r = [r for r in vr if r["case_id"] == "B3_pe_high_neg" and r["condition"] in cf.FIT_CONDS]
        tgt = b3r[0]["target"]
        band = b3r[0]["band"]
        lo = band[0] if band else tgt
        b3.append({"variant": vname, "n": len(b3r), "target_pct": 100 * tgt,
                   "band_lo_pct": 100 * band[0] if band else None, "band_hi_pct": 100 * band[1] if band else None,
                   "median_post_pct": 100 * statistics.median(r["post"] for r in b3r),
                   "pct_below_target": 100 * sum(r["post"] < tgt - 1e-12 for r in b3r) / len(b3r),
                   "pct_below_lo": 100 * sum(r["post"] < lo - 1e-12 for r in b3r) / len(b3r)})
    # macros
    for o in out:
        t = "cfAlt" + "".join(w.capitalize() for w in o["variant"].split("_")) + ("All" if o["model"] == "ALL" else model_tag(o["model"]))
        mac[t + "OverMedLod"] = tex_num(o["over_med_lod"])
        mac[t + "OverPctAbove"] = f"{o['over_pct_above']:.0f}"
        mac[t + "RatioMed"] = tex_num(o["ratio_med"])
        mac[t + "RatioNGtOne"] = str(o["ratio_n_gt1"])
        if "b" in o:
            mac[t + "ParBPt"] = tex_num(o["b"])
            mac[t + "ParBLo"] = tex_num(o["b_lo"])
            mac[t + "ParBHi"] = tex_num(o["b_hi"])
    for vname in variants:
        ms = [o for o in out if o["variant"] == vname and o["model"] != "ALL"]
        t = "cfAlt" + "".join(w.capitalize() for w in vname.split("_"))
        for k, tag in (("over_med_lod", "OverMedLod"), ("ratio_med", "RatioMed"), ("b", "ParB")):
            if all(k in o for o in ms):
                mac[t + tag + "Min"] = tex_num(min(o[k] for o in ms))
                mac[t + tag + "Max"] = tex_num(max(o[k] for o in ms))
        if all("b_lo" in o for o in ms):
            mac[t + "ParBCiAboveOneN"] = str(sum(o["b_lo"] > 1 for o in ms))
        mac[t + "OverPctAboveMin"] = f"{min(o['over_pct_above'] for o in ms):.0f}"
        mac[t + "OverPctAboveMax"] = f"{max(o['over_pct_above'] for o in ms):.0f}"
    for b in b3:
        t = "cfAltBThreeNeg" + "".join(w.capitalize() for w in b["variant"].split("_"))
        mac[t + "TargetPct"] = tex_num(b["target_pct"], 1)
        mac[t + "MedianPct"] = tex_num(b["median_post_pct"], 1)
        mac[t + "PctBelowTarget"] = f"{b['pct_below_target']:.0f}"
        mac[t + "PctBelowLo"] = f"{b['pct_below_lo']:.0f}"
        if b["band_lo_pct"] is not None:
            mac[t + "BandLoPct"] = tex_num(b["band_lo_pct"], 1)
            mac[t + "BandHiPct"] = tex_num(b["band_hi_pct"], 1)
    # inputs as macros (traceable to data/)
    pik = load_json(ALT)["pickhardt2011_mdct"]
    mac["cfAltPickLrPos"] = f"{pik['lr_pos']:g}"
    mac["cfAltPickLrPosRecomputed"] = f"{pik['lr_pos_recomputed']:g}"
    mac["cfAltPickLrNeg"] = f"{pik['lr_neg']:g}"
    sp = specs["pickhardt"]
    mac["cfAltPickBFivePosTargetPct"] = tex_num(100 * sp["B5_appy_ct_pos"]["target"], 1)
    mac["cfAltPickBFiveNegTargetPct"] = tex_num(100 * sp["B5_appy_ct_neg"]["target"], 2)
    mac["cfAltPickRecompBFivePosTargetPct"] = tex_num(100 * specs["pickhardt_recomputed"]["B5_appy_ct_pos"]["target"], 1)
    # table: one row per variant, pooled-over-model summaries plus per-model ranges
    lines = ["\\begin{tabular}{lrrrrr}", "\\toprule",
             "Targets & Over. after pos. & \\% above & Median $r$ & $b$ (pooled) & B3 neg. median / target \\\\",
             " & (log-odds, range) & (range) & (range) & (range) & (\\%) \\\\", "\\midrule"]
    for vname in variants:
        ms = [o for o in out if o["variant"] == vname and o["model"] != "ALL"]
        bb = [b for b in b3 if b["variant"] == vname][0]
        brange = (f"{tex_num(min(o['b'] for o in ms))} to {tex_num(max(o['b'] for o in ms))}"
                  if all("b" in o for o in ms) else "as above")
        tgt = (f"{bb['band_lo_pct']:.1f} to {bb['band_hi_pct']:.1f}" if bb["band_lo_pct"] is not None
               else f"{bb['target_pct']:.1f}")
        lines.append(f"{VARIANT_LABEL[vname]} & {tex_num(min(o['over_med_lod'] for o in ms))} to "
                     f"{tex_num(max(o['over_med_lod'] for o in ms))} & "
                     f"{min(o['over_pct_above'] for o in ms):.0f} to {max(o['over_pct_above'] for o in ms):.0f} & "
                     f"{tex_num(min(o['ratio_med'] for o in ms))} to {tex_num(max(o['ratio_med'] for o in ms))} & "
                     f"{brange} & {bb['median_post_pct']:.1f} / {tgt} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_tex(os.path.join(gen_dir, "table_alt_targets.tex"), lines)
    return out, b3


