def odds(p):
    return p / (1 - p)


def bayes(p, lr):
    o = odds(p) * lr
    return o / (1 + o)


def load_json(path):
    with open(path) as f:
        return json.load(f)


# ================================================================ F4 alternative targets
def alt_specs(cases, alt):
    """{variant: {case_id: {"lr": LR used for r and b, "target": point, "band": (lo, hi) or None}}}.

    Only the overridden cases appear; every other case keeps its primary target."""
    pio, pik = alt["pioped2_cta_lr"], alt["pickhardt2011_mdct"]
    v = {"primary": {}, "lr_ci_band": {}, "observed": {}, "observed_ci_band": {}, "pickhardt": {},
         "pickhardt_recomputed": {}, "all_alt": {}}
    for cid, c in cases.items():
        s, res, prior = c["scenario"], c["result"], c["target"]["pretest_point"]
        if s in pio["applies_to"]:
            lr_pt = pio["lr_pos"] if res == "pos" else pio["lr_neg"]
            ci = pio["lr_pos_ci"] if res == "pos" else pio["lr_neg_ci"]
            band = tuple(sorted(bayes(prior, x) for x in ci))
            steep = ci[1] if res == "pos" else ci[0]  # end of the CI with the largest DOR (least favourable to r > 1)
            v["lr_ci_band"][cid] = {"lr": steep, "target": bayes(prior, lr_pt), "band": band}
            st = [t for t in (c.get("sensitivity_targets") or []) if "PIOPED II observed" in t["label"]]
            assert len(st) == 1, cid
            obs = st[0]["value"]
            ob = {"lr": odds(obs) / odds(prior), "target": obs, "band": None}
            v["observed"][cid] = ob
            v["observed_ci_band"][cid] = dict(ob, band=tuple(st[0]["ci"]))
            v["all_alt"][cid] = ob
        if s in pik["applies_to"]:
            for name, lp in (("pickhardt", pik["lr_pos"]), ("pickhardt_recomputed", pik["lr_pos_recomputed"])):
                lr = lp if res == "pos" else (pik["lr_neg"] if name == "pickhardt" else pik["lr_neg_recomputed"])
                v[name][cid] = {"lr": lr, "target": bayes(prior, lr), "band": None}
            v["all_alt"][cid] = v["pickhardt"][cid]
    return v


