# ================================================================ F8 decision thresholds
PRIMARY = {"pe_test_kline", "pneumonia_test", "pneumonia_treat"}


def threshold_specs(cases, path=THR):
    """List of {id, label, value, case_ids, primary}. Rows with no usable value are skipped."""
    d = load_json(path)
    out = []

    def add(tid, label, val, cids, source):
        if val is None:
            return
        out.append({"id": tid, "label": label, "value": float(val), "case_ids": sorted(cids), "primary": tid in PRIMARY,
                    "source": source})
    for t in d["thresholds"]:
        cids = [cid for cid, c in cases.items() if c["scenario"] in t["cases"]]
        sc = t["scenario"]
        if sc == "PE":
            add("pe_test_kline", "PE test 1.8% (Kline 2004)", t["test_threshold"], cids, t["source_key"])
            for a in t.get("alternatives", []):
                add("pe_test_lessler", "PE test 1.4% (Lessler 2010)", a["test_threshold"], cids, a["source_key"])
        elif sc == "pneumonia":
            add("pneumonia_test", "Pneumonia test 9.5% (Ebell 2018)", t["test_threshold"], cids, t["source_key"])
            add("pneumonia_treat", "Pneumonia treatment 43.1% (Ebell 2018)", t["treatment_threshold"], cids, t["source_key"])
            u = t.get("updated_after_model_probability") or {}
            add("pneumonia_test_updated", "Pneumonia test 12.7% (Ebell, updated)", u.get("test"), cids, t["source_key"])
            add("pneumonia_treat_updated", "Pneumonia treatment 51.3% (Ebell, updated)", u.get("treatment"), cids, t["source_key"])
        elif sc == "aortic_dissection":
            add("aas_test", "AAS no test vs CTA 0.03% (Taylor 2013)", t["test_threshold"], cids, t["source_key"])
            add("aas_ddimer_cta", "AAS D-dimer vs CTA 0.6% (Taylor 2013)", t.get("ddimer_vs_cta_threshold"), cids, t["source_key"])
            rng = t.get("test_threshold_range_by_age") or [None, None]
            add("aas_cta_age_lo", "AAS CTA, youngest 0.3% (Taylor 2013)", rng[0], cids, t["source_key"])
            add("aas_cta_age_hi", "AAS CTA, oldest 2.1% (Taylor 2013)", rng[1], cids, t["source_key"])
        elif sc == "appendicitis":
            up = t.get("upper_imaging_threshold") or {}
            for mod, val in up.items():
                tag = "ct" if mod.upper() == "CT" else "us"
                add(f"appy_upper_{tag}", f"Appendicitis operate without imaging {100 * val:.0f}% ({mod}, Van Hoe 2000)", val,
                    [c for c in cids if f"_{tag}_" in c], t["source_key"])
        else:
            add(f"{sc}_test", f"{sc} test", t.get("test_threshold"), cids, t["source_key"])
            add(f"{sc}_treat", f"{sc} treatment", t.get("treatment_threshold"), cids, t["source_key"])
    assert PRIMARY <= {s["id"] for s in out}, "a primary threshold is missing from decision_thresholds.json"
    return out


def side(p, thr):
    return "above" if p >= thr else "below"


def is_fragile(target, thr):
    return max(target / thr, thr / target) <= FRAGILE if target > 0 else False


def discordance(rows, specs, cond_groups=(("VNBS", cf.FIT_CONDS), ("E", ["E"]))):
    per, cases_out = [], []
    models = cf.models_of(rows)
    for sp in specs:
        thr = sp["value"]
        for cg, conds in cond_groups:
            sel = [r for r in rows if r["case_id"] in sp["case_ids"] and r["condition"] in conds]
            if not sel:
                continue
            for cid in sp["case_ids"]:
                cr = [r for r in sel if r["case_id"] == cid]
                if not cr:
                    continue
                tgt = cr[0]["target"]
                ts = side(tgt, thr)
                row = {"threshold": sp["id"], "cond_group": cg, "case_id": cid, "threshold_pct": 100 * thr,
                       "target_pct": 100 * tgt, "target_side": ts, "fragile": int(is_fragile(tgt, thr)), "n": len(cr)}
                for m in models + ["ALL"]:
                    mr = [r for r in cr if m == "ALL" or r["model"] == m]
                    row["pct_other_side_" + m] = (100 * sum(side(r["post"], thr) != ts for r in mr) / len(mr)) if mr else None
                cases_out.append(row)
            for m in models + ["ALL"]:
                for excl in (False, True):
                    mr = [r for r in sel if (m == "ALL" or r["model"] == m)
                          and not (excl and is_fragile(r["target"], thr))]
                    tb = [r for r in mr if side(r["target"], thr) == "below"]
                    ta = [r for r in mr if side(r["target"], thr) == "above"]
                    fa = sum(side(r["post"], thr) == "above" for r in tb)
                    fr = sum(side(r["post"], thr) == "below" for r in ta)
                    per.append({"threshold": sp["id"], "label": sp["label"], "primary": int(sp["primary"]),
                                "threshold_pct": 100 * thr, "cond_group": cg, "model": m,
                                "excl_fragile": int(excl), "n": len(mr),
                                "n_target_below": len(tb), "n_false_alarm": fa,
                                "false_alarm_rate": 100 * fa / len(tb) if tb else None,
                                "n_target_above": len(ta), "n_false_reassurance": fr,
                                "false_reassurance_rate": 100 * fr / len(ta) if ta else None,
                                "discordance_rate": 100 * (fa + fr) / len(mr) if mr else None,
                                "fragile_cases": ";".join(c for c in sp["case_ids"]
                                                          if any(r["case_id"] == c and is_fragile(r["target"], thr) for r in sel))})
    return per, cases_out


def f8(rows, cases, mac, gen_dir, path=THR):
    specs = threshold_specs(cases, path)
    per, cs = discordance(rows, specs)
    tid_tag = lambda s: "".join(w.capitalize() for w in s.split("_"))  # noqa: E731
    for p in per:
        t = ("cfThr" + tid_tag(p["threshold"]) + ("E" if p["cond_group"] == "E" else "")
             + ("NoFrag" if p["excl_fragile"] else "") + ("All" if p["model"] == "ALL" else model_tag(p["model"])))
        if p["false_alarm_rate"] is not None:
            mac[t + "FaPct"] = f"{p['false_alarm_rate']:.0f}"
            mac[t + "FaN"] = str(p["n_false_alarm"])
            mac[t + "TbN"] = str(p["n_target_below"])
        if p["false_reassurance_rate"] is not None:
            mac[t + "FrPct"] = f"{p['false_reassurance_rate']:.0f}"
            mac[t + "FrN"] = str(p["n_false_reassurance"])
            mac[t + "TaN"] = str(p["n_target_above"])
        if p["discordance_rate"] is not None:
            mac[t + "DiscPct"] = f"{p['discordance_rate']:.0f}"
            mac[t + "N"] = str(p["n"])
    for sp in specs:
        tt = "cfThr" + tid_tag(sp["id"])
        mac[tt + "ValuePct"] = f"{100 * sp['value']:g}"
        fr = [c for c in cs if c["threshold"] == sp["id"] and c["cond_group"] == "VNBS" and c["fragile"]]
        mac[tt + "NFragileCases"] = str(len(fr))
        mac[tt + "NCases"] = str(len([c for c in cs if c["threshold"] == sp["id"] and c["cond_group"] == "VNBS"]))
    for c in cs:  # per case: percent of answers on the other side of the threshold than the target
        if c["threshold"] not in PRIMARY and c["threshold"] != "pe_test_lessler":
            continue
        ctag = "".join(w[0].upper() + w[1:] for w in c["case_id"].replace("A1", "AOne").replace("B1", "BOne")
                       .replace("B2", "BTwo").replace("B3", "BThree").split("_"))
        for m in cf.models_of(rows) + ["ALL"]:
            v = c["pct_other_side_" + m]
            if v is not None:
                mac["cfThrCase" + ctag + tid_tag(c["threshold"]) + ("E" if c["cond_group"] == "E" else "")
                    + ("All" if m == "ALL" else model_tag(m)) + "OtherPct"] = f"{v:.0f}"
        if c["cond_group"] == "VNBS":
            mac["cfThrCase" + ctag + tid_tag(c["threshold"]) + "TargetPct"] = tex_num(c["target_pct"], 2)
            mac["cfThrCase" + ctag + tid_tag(c["threshold"]) + "Fragile"] = "yes" if c["fragile"] else "no"
    for sid in sorted(PRIMARY):
        ms = [p for p in per if p["threshold"] == sid and p["cond_group"] == "VNBS" and not p["excl_fragile"]
              and p["model"] != "ALL"]
        for k, tag in (("false_alarm_rate", "Fa"), ("false_reassurance_rate", "Fr")):
            v = [p[k] for p in ms if p[k] is not None]
            if v:
                mac["cfThr" + tid_tag(sid) + tag + "PctMin"] = f"{min(v):.0f}"
                mac["cfThr" + tid_tag(sid) + tag + "PctMax"] = f"{max(v):.0f}"
    # compact paper table: primary thresholds, V N B S, per model: false alarm % (k/n) and false reassurance % (k/n)
    order = ["pe_test_kline", "pneumonia_test", "pneumonia_treat"]
    hdr = {"pe_test_kline": "PE, test 1.8\\%", "pneumonia_test": "Pneumonia, test 9.5\\%",
           "pneumonia_treat": "Pneumonia, treat 43.1\\%"}
    lines = ["\\begin{tabular}{l" + "rr" * len(order) + "}", "\\toprule",
             " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{hdr[o]}}}" for o in order) + " \\\\",
             "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(order))),
             "Model" + " & FA & FR" * len(order) + " \\\\", "\\midrule"]

    def cell(p, k, nk, dk):
        return "none" if p[k] is None else f"{p[k]:.0f} ({p[nk]}/{p[dk]})"
    for m in cf.models_of(rows) + ["ALL"]:
        parts = []
        for o in order:
            p = [x for x in per if x["threshold"] == o and x["model"] == m and x["cond_group"] == "VNBS"
                 and not x["excl_fragile"]][0]
            parts += [cell(p, "false_alarm_rate", "n_false_alarm", "n_target_below"),
                      cell(p, "false_reassurance_rate", "n_false_reassurance", "n_target_above")]
        name = "All models" if m == "ALL" else display_name(m)
        lines.append(("\\midrule\n" if m == "ALL" else "") + name + " & " + " & ".join(parts) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_tex(os.path.join(gen_dir, "table_thresholds.tex"), lines)
    return per, cs, specs


THR_FIELDS = ["threshold", "label", "primary", "threshold_pct", "cond_group", "model", "excl_fragile", "n",
              "n_target_below", "n_false_alarm", "false_alarm_rate", "n_target_above", "n_false_reassurance",
              "false_reassurance_rate", "discordance_rate", "fragile_cases"]


# ================================================================ main
def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default=os.path.join(ROOT, "results", "raw", "*.jsonl"))
    ap.add_argument("--cases", default=os.path.join(ROOT, "data", "cases"))
    ap.add_argument("--out", default=os.path.join(ROOT, "results", "derived"))
    ap.add_argument("--generated", default=os.path.join(ROOT, "paper", "generated"))
    ap.add_argument("--n-boot", type=int, default=2000)
    add_run_args(ap)
    a = ap.parse_args(argv)
    allowed, run_set, cfg = resolve_run_ids(a)
    cases, final, rows, syn = cf.load_rows(a.raw, a.cases, allowed, cfg)
    for d in (a.out, a.generated):
        guard_output(d, syn)
    guard_pilot(a.generated, run_set)
    mac, res = {}, {}
    alt, b3 = f4(rows, cases, a.n_boot, mac, a.generated)
    write_csv(os.path.join(a.out, "cf2_alt_targets.csv"), alt, ALT_FIELDS)
    write_csv(os.path.join(a.out, "cf2_alt_b3neg.csv"), b3, B3_FIELDS)
    h4 = f5(rows, mac)
    write_csv(os.path.join(a.out, "cf2_h4_groups.csv"), h4, H4_FIELDS)
    per, cs, specs = f8(rows, cases, mac, a.generated)
    write_csv(os.path.join(a.out, "cf2_thresholds.csv"), per, THR_FIELDS)
    models = cf.models_of(rows)
    write_csv(os.path.join(a.out, "cf2_threshold_cases.csv"), cs,
              ["threshold", "cond_group", "case_id", "threshold_pct", "target_pct", "target_side", "fragile", "n"]
              + ["pct_other_side_" + m for m in models + ["ALL"]])
    res.update(alt=alt, b3=b3, h4=h4, thr=per, thr_cases=cs, specs=specs)
    path = os.path.join(a.generated, "committee_macros2.tex")
    cf.write_macros(path, mac)
    with open(path) as f:
        txt = f.read().replace("committee_fixes.py", "committee_fixes2.py", 1)
    with open(path, "w") as f:
        f.write(txt)
    print(f"committee_fixes2: {len(rows)} analysed rows, {len(mac)} macros")
    return res, mac


if __name__ == "__main__":
    main()
