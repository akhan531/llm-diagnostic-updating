# ================================================================ F5 H4 by removed-item type
def e_groups(path=ECLASS):
    """{scenario: {"any_component": bool, "score_item": bool}}. any_component: at least one removed negative
    is a score item or part of the source-vignette definition (case builder's flag). score_item: at least one
    removed negative is an item of a clinical score (Wells, ADD-RS, Alvarado), basis 'score item'."""
    d = load_json(path)
    g = {}
    for r in d["rows"]:
        e = g.setdefault(r["scenario"], {"any_component": False, "score_item": False})
        e["any_component"] |= bool(r["score_component"])
        e["score_item"] |= r["basis"] == "score item"
    for s, n in d["summary_per_scenario"].items():
        assert (n["score_component"] > 0) == g[s]["any_component"], s
    return g


def perm_diff_p(vals, in_group):
    """Exact two-sided permutation p for the difference in group means (all relabellings)."""
    n1 = sum(in_group)
    obs = abs(statistics.mean([v for v, g in zip(vals, in_group) if g]) -
              statistics.mean([v for v, g in zip(vals, in_group) if not g])) - 1e-12
    cnt = tot = 0
    for idx in itertools.combinations(range(len(vals)), n1):
        s = set(idx)
        a = [vals[i] for i in s]
        b = [vals[i] for i in range(len(vals)) if i not in s]
        tot += 1
        cnt += abs(statistics.mean(a) - statistics.mean(b)) >= obs
    return cnt / tot


def f5(rows, mac, groups=None):
    groups = groups or e_groups()
    sc = cf.scenario_contrasts(rows, "E", "N", "signed")
    allm = {}
    for m in sc:
        for s, v in sc[m].items():
            allm.setdefault(s, []).append(v)
    series = [(m, sc[m]) for m in sorted(sc)] + [("ALL", {s: statistics.mean(v) for s, v in allm.items()})]
    out = []
    for split in ("any_component", "score_item"):
        for m, d in series:
            scen = sorted(d)
            flags = [groups[s][split] for s in scen]
            for gval in (True, False):
                vals = [d[s] for s, f in zip(scen, flags) if f == gval]
                if not vals:
                    continue
                lo, hi = cf.signflip_ci(vals) if len(vals) >= 2 else (None, None)
                out.append({"split": split, "group": "yes" if gval else "no", "model": m, "n_scen": len(vals),
                            "scenarios": ";".join(s for s, f in zip(scen, flags) if f == gval),
                            "mean": statistics.mean(vals), "lo": lo, "hi": hi,
                            "p_signflip": cf.signflip_p(vals), "n_scen_pos": sum(v > 0 for v in vals),
                            "diff_yes_minus_no": None, "p_perm_diff": None})
            if 0 < sum(flags) < len(flags):
                diff = (statistics.mean([d[s] for s, f in zip(scen, flags) if f]) -
                        statistics.mean([d[s] for s, f in zip(scen, flags) if not f]))
                for o in out[-2:]:
                    o["diff_yes_minus_no"] = diff
                    o["p_perm_diff"] = perm_diff_p([d[s] for s in scen], flags)
    for o in out:
        t = ("cfHFour" + ("Comp" if o["split"] == "any_component" else "Score") + ("Yes" if o["group"] == "yes" else "No")
             + ("All" if o["model"] == "ALL" else model_tag(o["model"])))
        mac[t + "Mean"] = tex_num(o["mean"])
        mac[t + "N"] = str(o["n_scen"])
        mac[t + "NPos"] = str(o["n_scen_pos"])
        mac[t + "P"] = cf.fmt_p(o["p_signflip"]) if o["n_scen"] >= 2 else "n/a"
        if o["lo"] is not None:
            mac[t + "Lo"] = tex_num(o["lo"])
            mac[t + "Hi"] = tex_num(o["hi"])
        if o["diff_yes_minus_no"] is not None and o["group"] == "yes":
            tt = t.replace("Yes", "Diff", 1)
            mac[tt] = tex_num(o["diff_yes_minus_no"])
            mac[tt + "P"] = cf.fmt_p(o["p_perm_diff"])
    for split, tag in (("any_component", "Comp"), ("score_item", "Score")):
        for gv, gt in (("yes", "Yes"), ("no", "No")):
            ms = [o for o in out if o["split"] == split and o["group"] == gv and o["model"] != "ALL"]
            if ms:
                mac[f"cfHFour{tag}{gt}MeanMin"] = tex_num(min(o["mean"] for o in ms))
                mac[f"cfHFour{tag}{gt}MeanMax"] = tex_num(max(o["mean"] for o in ms))
                mac[f"cfHFour{tag}{gt}NPosModels"] = str(sum(o["mean"] > 0 for o in ms))
    return out


