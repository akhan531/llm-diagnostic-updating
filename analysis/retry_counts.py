"""Count network-level call_error records (no reply received) that were re-sent, per run, from results/raw.

A call_error record is 'retried' when a later record exists for the same (case, condition, model, seed)
with a parsed-or-unparsed reply (parse_status != call_error). Failed attempts stay in the raw log and are
excluded from analysis counts. pilot1 (old prompt, 401 errors) is excluded from the paper and not counted.

Outputs: results/derived/retry_counts.csv, paper/generated/retry_macros.tex
Macros: \\nRetriedNoReply (main1 + ext1..ext5, the runs the paper's first drafts describe),
\\nRetriedNoReplyMain, \\nRetriedNoReplyFollowup, \\nRetriedNoReplyAllRuns (adds ext6, ext7, ext8), \\nNotResentNoReply (call_error records with no
reply that were never re-sent, all runs; 2: ext6_para2 and ext7_newcases, DeepSeek seed 3), and per run
\\nRetriedNoReplyRun<Name>. Usage: python analysis/retry_counts.py
"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT, write_csv  # noqa: E402

RAW = os.path.join(ROOT, "results", "raw")
CORE = ["main1", "ext1_pretest", "ext2_belief", "ext3_long", "ext4_unnamed", "ext5_dsretry"]
LATER = ["ext6_para1", "ext6_para2", "ext7_newcases", "ext8_family"]
NAME = {"main1": "MainOne", "ext1_pretest": "ExtOne", "ext2_belief": "ExtTwo", "ext3_long": "ExtThree",
        "ext4_unnamed": "ExtFour", "ext5_dsretry": "ExtFive", "ext6_para1": "ExtSixParaOne",
        "ext6_para2": "ExtSixParaTwo", "ext7_newcases": "ExtSeven", "ext8_family": "ExtEight"}


def count_run(run):
    path = os.path.join(RAW, run + ".jsonl")
    recs = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                recs.append(json.loads(line))
            except json.JSONDecodeError:
                continue  # a line being written by a concurrent batch
    key = lambda r: (r["case_id"], r["condition"], r["model"], str(r.get("seed")))  # noqa: E731
    replied = {key(r) for r in recs if r.get("parse_status") != "call_error"}
    errs = [r for r in recs if r.get("parse_status") == "call_error"]
    resent = [r for r in errs if key(r) in replied]
    return len(recs), len(errs), len(resent)


def main():
    rows, mac = [], {}
    for run in CORE + LATER:
        if not os.path.exists(os.path.join(RAW, run + ".jsonl")):
            continue
        n, e, rs = count_run(run)
        rows.append({"run_id": run, "n_records": n, "n_call_error": e, "n_resent": rs})
        mac["nRetriedNoReplyRun" + NAME[run].replace(" ", "")] = rs
    by = {r["run_id"]: r["n_resent"] for r in rows}
    # every core-run error was re-sent; later runs may hold an error not (yet) re-sent (ext6_para2: 1, ext7 in progress), reported in the csv
    assert all(r["n_call_error"] == r["n_resent"] for r in rows if r["run_id"] in CORE), rows
    mac["nRetriedNoReplyMain"] = by["main1"]
    mac["nRetriedNoReplyFollowup"] = sum(by.get(r, 0) for r in CORE[1:])
    mac["nRetriedNoReply"] = sum(by.get(r, 0) for r in CORE)
    mac["nRetriedNoReplyAllRuns"] = sum(by.values())
    mac["nNotResentNoReply"] = sum(r["n_call_error"] - r["n_resent"] for r in rows)
    # key numbers from the I6 scan (run 21); later runs may add more, core runs must not change
    assert by["main1"] == 6 and by["ext2_belief"] == 1 and by["ext4_unnamed"] == 1, by
    assert mac["nRetriedNoReply"] == 8, mac
    # R3 M1: the two DeepSeek seed-3 failures that were never re-sent; the ext8 error was re-sent (1 of 1)
    assert by["ext8_family"] == 1 and mac["nNotResentNoReply"] == 2, (by, mac)
    assert {r["run_id"] for r in rows if r["n_call_error"] != r["n_resent"]} == {"ext6_para2", "ext7_newcases"}
    os.makedirs(os.path.join(ROOT, "results", "derived"), exist_ok=True)
    write_csv(os.path.join(ROOT, "results", "derived", "retry_counts.csv"), rows,
              ["run_id", "n_records", "n_call_error", "n_resent"])
    gen = os.path.join(ROOT, "paper", "generated")
    with open(os.path.join(gen, "retry_macros.tex"), "w") as f:
        f.write("% GENERATED by analysis/retry_counts.py from results/raw. Do not edit.\n")
        for k in sorted(mac):
            assert k.isalpha()
            f.write(f"\\newcommand{{\\{k}}}{{{mac[k]}}}\n")
    print(rows, mac)


if __name__ == "__main__":
    main()
